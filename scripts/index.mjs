#!/usr/bin/env node
// Regenerate the compact active index in a Context directory's AGENTS.md,
// validate active markup frontmatter, check Markdown links, say when a consolidation pass is
// due, check that an instruction file imports the index, and keep Context-Inbox out of Git.
//
// Usage: node scripts/index.mjs <path-to-Context> [--nested] [--links=<folder>] [--check] [--consolidated[=YYYY-MM-DD]] [--cadence=<days>] [--force]
//
// The block is guard-delimited and idempotent. Content outside the block is
// preserved. Every Archive folder is left out of the active index at any depth. The
// consolidation marker is one comment line directly above the block, outside the
// guards, so an older copy of this script leaves it alone, and the folders --links
// named sit in a second comment line under it. The script knows only its current
// name: after a rename, every existing index is regenerated by hand.

import { readFileSync, writeFileSync, appendFileSync, existsSync, readdirSync, statSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { join, relative, resolve, basename, extname, dirname, isAbsolute } from "node:path";

